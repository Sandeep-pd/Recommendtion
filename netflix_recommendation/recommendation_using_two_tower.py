import torch
import torch.nn as nn
import torch.nn.functional as F

EMBED_DIM = 64
NUM_HEADS = 4
NUM_LAYERS = 2

class ItemTower(nn.Module):

    def __init__(self, vocab_size, embed_dim=64):

        super().__init__()

        self.embedding = nn.Embedding(
            vocab_size,
            embed_dim,
            padding_idx=0
        )

        self.position_embedding = nn.Embedding(
            MAX_LEN,
            embed_dim
        )

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=embed_dim,
            nhead=NUM_HEADS,
            dim_feedforward=128,
            dropout=0.1,
            batch_first=True
        )

        self.transformer = nn.TransformerEncoder(
            encoder_layer,
            num_layers=NUM_LAYERS
        )

        self.projection = nn.Linear(
            embed_dim,
            embed_dim
        )

    def forward(self, tokens):

        batch_size, seq_len = tokens.shape

        positions = torch.arange(
            seq_len,
            device=tokens.device
        ).unsqueeze(0).expand(batch_size, -1)

        x = self.embedding(tokens)

        x = x + self.position_embedding(positions)

        padding_mask = tokens == 0

        x = self.transformer(
            x,
            src_key_padding_mask=padding_mask
        )

        # Mean pooling, ignoring padding tokens
        mask = (~padding_mask).unsqueeze(-1)

        x = (x * mask).sum(dim=1)

        x = x / mask.sum(dim=1).clamp(min=1)

        x = self.projection(x)

        return F.normalize(x, p=2, dim=1)

class UserTower(nn.Module):

    def __init__(self, num_items, embed_dim=64):

        super().__init__()

        # Extra ID reserved for padding
        self.item_embedding = nn.Embedding(
            num_items + 1,
            embed_dim,
            padding_idx=num_items
        )

        self.position_embedding = nn.Embedding(
            MAX_HISTORY,
            embed_dim
        )

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=embed_dim,
            nhead=NUM_HEADS,
            dim_feedforward=128,
            dropout=0.1,
            batch_first=True
        )

        self.transformer = nn.TransformerEncoder(
            encoder_layer,
            num_layers=NUM_LAYERS
        )

        self.projection = nn.Linear(
            embed_dim,
            embed_dim
        )

    def forward(self, history):

        batch_size, seq_len = history.shape

        positions = torch.arange(
            seq_len,
            device=history.device
        ).unsqueeze(0).expand(batch_size, -1)

        x = self.item_embedding(history)

        x = x + self.position_embedding(positions)

        padding_mask = history == NUM_ITEMS

        x = self.transformer(
            x,
            src_key_padding_mask=padding_mask
        )

        mask = (~padding_mask).unsqueeze(-1)

        x = (x * mask).sum(dim=1)

        x = x / mask.sum(dim=1).clamp(min=1)

        x = self.projection(x)

        return F.normalize(x, p=2, dim=1)

class TwoTowerTransformer(nn.Module):

    def __init__(self, vocab_size, num_items):

        super().__init__()

        self.user_tower = UserTower(num_items)

        self.item_tower = ItemTower(vocab_size)

    def forward(self, user_history, item_tokens):

        user_vector = self.user_tower(user_history)

        item_vector = self.item_tower(item_tokens)

        scores = torch.sum(
            user_vector * item_vector,
            dim=1
        )

        return scores

